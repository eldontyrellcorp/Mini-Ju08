"""The QR code of the About screen -> firmware/src/ju_qr.h (needs the `qrcode` package; the result is checked in, builds do not run this).
  python3 tools/gen_qr.py [url] [out.h]"""
import sys
import qrcode

url = sys.argv[1] if len(sys.argv) > 1 else "https://github.com/eldontyrellcorp/Mini-Ju08"
out = sys.argv[2] if len(sys.argv) > 2 else "firmware/src/ju_qr.h"
qr = qrcode.QRCode(version=None, error_correction=qrcode.constants.ERROR_CORRECT_M, border=0)
qr.add_data(url)
qr.make(fit=True)
m = qr.get_matrix()
n = len(m)
nb = (n + 7) // 8
rows = []
for r in m:
    b = [0] * nb
    for c, v in enumerate(r):
        if v:
            b[c >> 3] |= 1 << (c & 7)
    rows.append("    {" + ", ".join("0x%02X" % x for x in b) + "},")
text = "/* Generated by tools/gen_qr.py: do not edit. %s */\n#define JU_QR_N %d\n#define JU_QR_B %d\nstatic const uint8_t JU_QR[JU_QR_N][JU_QR_B] = {\n%s\n};\n" % (url, n, nb, "\n".join(rows))
open(out, "w").write(text)
print(f"{out}: {n}x{n} modules (version {qr.version}) for {url}")
