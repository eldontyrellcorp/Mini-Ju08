"""Tables for the fixed-point Jupiter-8 engine (firmware/src/ju_dsp.c) -> firmware/src/ju_tables.h.

Every mapping is the one in jupiter8_esp32/src/dsp/params.cpp, evaluated here so the firmware needs no float.
FS = 44100, control block = 32 samples (the same as the ESP32 engine's kBlock).
  python3 tools/gen_ju_tables.py [out.h]"""
import math
import sys

FS = 44100.0
BLOCK = 32
DT = BLOCK / FS


def n(v):
    return v / 255.0


def arr(name, ctype, vals, per=8):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(int(x)) + ("u" if ctype.startswith("u") else "") for x in vals[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


def clampu(x):
    return max(0, min(0xFFFFFFFF, int(round(x))))


def q(x, bits):
    return int(round(x * (1 << bits)))


L = ["/* Generated by tools/gen_ju_tables.py: do not edit. */", "#pragma once", ""]

# tanh over [-4, 4], step 1/64, Q24 (JU_SAT_N intervals + 1 guard)
L.append("#define JU_SAT_N 512")
L.append(arr("JU_SAT", "int32_t", [q(math.tanh(-4 + i / 64.0), 24) for i in range(514)]))

# one-pole / ladder coefficient g = T / (1 + T), T = tan(pi fc / FS), by log2(fc), 1/32 octave, from 4 Hz (log2 = 2), Q30
G_L0, G_STEP, G_N = 2, 32, 402
gt = []
for i in range(G_N):
    fc = min(2 ** (G_L0 + i / G_STEP), 0.46 * FS)
    t = math.tan(math.pi * fc / FS)
    gt.append(clampu((t / (1 + t)) * (1 << 30)))
L.append(f"#define JU_G_L0 {G_L0}   /* log2 of the first frequency (Hz) */\n#define JU_G_N {G_N}")
L.append(arr("JU_G", "uint32_t", gt))

# phase increment of A4 * 2^(i/256): 2^32 * 440 / FS * 2^(i/256)
K = (1 << 32) * 440.0 / FS
L.append(arr("JU_INC", "uint32_t", [clampu(K * 2 ** (i / 256.0)) for i in range(257)]))
# 2^(i/256) in Q16 and 2^(-i/256) in Q30
L.append(arr("JU_EXP2P", "uint32_t", [q(2 ** (i / 256.0), 16) for i in range(257)]))
L.append(arr("JU_EXP2N", "uint32_t", [q(2 ** (-i / 256.0), 30) for i in range(257)]))
# sine, one turn in 256 steps, Q24
L.append(arr("JU_SINE", "int32_t", [q(math.sin(2 * math.pi * i / 256.0), 24) for i in range(257)]))
# (note - 69) / 12 in Q16 octaves
L.append(arr("JU_NOTE_OCT", "int32_t", [q((i - 69) / 12.0, 16) for i in range(128)]))


def log2coef(tau):
    """magnitude of log2 of the per-block coefficient exp(-DT / tau), Q24"""
    return clampu(1.442695 * DT / tau * (1 << 24))


# ---- the 256-value mappings of params.cpp
att, dec, porta, lfo_inc, lfo_dly, rise, arp = [], [], [], [], [], [], []
res, vlo, veo, vfe, vfl, xm, v2t, hpf = [], [], [], [], [], [], [], []
for v in range(256):
    x = n(v)
    T = 0.001 * 2 ** (12.2877 * x)                    # attack time (to 1.25 -> 1.0 RC: tau = 0.62133 T)
    att.append(log2coef(T * 0.62133))
    T = 0.001 * 2 ** (13.2877 * x)                    # decay / release: 1% of the span at T, tau = 0.21715 T
    dec.append(log2coef(T * 0.21715))
    pt = 0.0 if v == 0 else 0.002 * 2 ** (10.5507 * x)
    porta.append(0 if v == 0 else log2coef(pt * 0.4))
    lfo_inc.append(clampu(0.05 * 2 ** (9.6439 * x) * DT * (1 << 32)))
    dly = 4.0 * x * x
    lfo_dly.append(65536 if dly <= 1e-4 else min(65536, q(DT / dly, 16)))
    arp.append(clampu(2 ** (4.3219 * x) * DT * (1 << 32)))      # mapArpRate: 1 - 20 Hz
    rs = 5.0 * x * x
    rise.append(65536 if rs <= 0.001 else min(65536, q(DT / rs, 16)))
    res.append(q(3.85 * x * (0.35 + 0.65 * x), 24))
    vlo.append(q(3.0 * x * x, 16))
    veo.append(q(5.0 * x * x, 16))
    vfe.append(q(9.0 * x, 16))
    vfl.append(q(4.0 * x * x, 16))
    xm.append(q(3.5 * x * x, 16))
    v2t.append(q((v - 128) * (50.0 / 127.0) / 1200.0, 16))
L.append("/* attack / decay / release / portamento: -log2 of the per-block coefficient, Q24 */")
L.append(arr("JU_ATT", "uint32_t", att))
L.append(arr("JU_DEC", "uint32_t", dec))
L.append(arr("JU_PORTA", "uint32_t", porta))
L.append("/* LFO phase increment per block (full turn = 2^32); delay and mod-rise steps per block, Q16 */")
L.append(arr("JU_LFO_INC", "uint32_t", lfo_inc))
L.append(arr("JU_LFO_DLY", "uint32_t", lfo_dly))
L.append(arr("JU_RISE", "uint32_t", rise))
L.append(arr("JU_ARP_INC", "uint32_t", arp))
L.append("/* resonance k (Q24); modulation depths and the VCO-2 fine tune in octaves (Q16) */")
L.append(arr("JU_RES", "int32_t", res))
L.append(arr("JU_VCO_LFO", "int32_t", vlo))
L.append(arr("JU_VCO_ENV", "int32_t", veo))
L.append(arr("JU_VCF_ENV", "int32_t", vfe))
L.append(arr("JU_VCF_LFO", "int32_t", vfl))
L.append(arr("JU_XMOD", "int32_t", xm))
L.append(arr("JU_V2TUNE", "int32_t", v2t))

text = "\n".join(L)
out = sys.argv[1] if len(sys.argv) > 1 else "firmware/src/ju_tables.h"
open(out, "w").write(text)
print(f"{out}: {len(text)} bytes of source")
